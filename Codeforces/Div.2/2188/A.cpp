void solve(){
    ll n;
    cin >> n;

    vector<ll> a(n);

    ll k = n;
    for(int i=n-1; i>=0; i-=2){
    	a[i]= k;
    	k--;
    }

    ll s = 1;
    for(int i=n-2; i>=0; i-=2){
    	a[i] = s;
    	s++;
    }

    for(auto it:a){
    	cout << it << " ";
    }
    cout << endl;
}

